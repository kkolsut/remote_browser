"""Podman Quadlet units of the remote browser, shared by sync-freeipa-users.py and install-units.py.

  QUADLET_DIR/rb-frontend.network     Nginx's own network: the published port and its way to Authelia
  QUADLET_DIR/rb-nginx.container      Nginx (install-units.py)
  QUADLET_DIR/rb-net-<uid>.network    one network per user, from BROWSER_NET_POOL (the sync)
  QUADLET_DIR/browser-<uid>.container the user's browser, alone with Nginx on rb-net-<uid> (the sync)

Podman's generator turns these into rb-nginx.service, browser-<uid>.service, rb-net-<uid>-network.service
and so on at every `systemctl daemon-reload`. Nginx joins the user networks live (`podman network
connect`, by the sync and by `sync-freeipa-users.py --attach-only` after Nginx starts): listing them in
rb-nginx.container would restart Nginx, and end every open stream, whenever a user is added.

Quadlet copies values into the ExecStart= line, where systemd would expand $ and %: every value that
comes from configuration is checked by safe() first. Nginx's environment, which needs a $ (the envsubst
filter), goes through an env file instead.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

QUADLET_DIR = "/etc/containers/systemd/remote-browser"
GENERATORS = ("/usr/lib/systemd/system-generators/podman-system-generator", "/usr/libexec/podman/quadlet")

FRONTEND = "rb-frontend"
NGINX = "rb-nginx"
NGINX_IMAGE = "docker.io/library/nginx:1.30.5-alpine"
BROWSER_PREFIX = "browser-"
NETWORK_PREFIX = "rb-net-"
USER_LABEL = "io.remote-browser.user"
EGRESS_UNIT = "remote-browser-egress.service"
# Nginx's default route must be the frontend network: through a user network its requests to Authelia
# would be egress-filtered. User networks get Podman's default metric, 100.
FRONTEND_METRIC = 50

# Characters that pass unchanged through Quadlet and systemd's ExecStart= parsing.
_SAFE = re.compile(r"[A-Za-z0-9._:/,+@=-]*")


class UnitError(Exception):
    pass


def safe(name: str, value: str) -> str:
    if not _SAFE.fullmatch(value):
        raise UnitError(f"{name}={value!r}: only letters, digits and ._:/,+@=- are allowed")
    return value


def browser_unit(uid: str) -> str:
    return f"{BROWSER_PREFIX}{uid}.service"


def network_unit(uid: str) -> str:
    return f"{NETWORK_PREFIX}{uid}-network.service"


def network_name(uid: str) -> str:
    return f"{NETWORK_PREFIX}{uid}"


def render(header: list[str], sections: list[tuple[str, list[tuple[str, str] | str]]]) -> str:
    """A unit file; a plain string inside a section is a comment line."""
    out = [f"# {line}" if line else "#" for line in header]
    for name, entries in sections:
        out += ["", f"[{name}]"]
        for e in entries:
            out.append(f"# {e}" if isinstance(e, str) else f"{e[0]}={e[1]}")
    return "\n".join(out) + "\n"


# --- per-user units (the sync) -------------------------------------------------------------------

@dataclass(frozen=True)
class BrowserConfig:
    image: str
    tz: str
    public_host: str
    public_port: str
    file_transfers: str
    user_data_root: Path


GENERATED = "Generated by scripts/sync-freeipa-users.py from FreeIPA. Do not edit: the next sync overwrites it."


def user_network(uid: str, subnet: str) -> str:
    return render([GENERATED], [
        ("Unit", [("Description", f"Remote browser: network of {uid}")]),
        ("Network", [
            ("NetworkName", network_name(uid)),
            ("Subnet", subnet),
            ("Label", f"{USER_LABEL}={uid}"),
        ]),
    ])


