# --- Nginx and its network (install-units.py) ----------------------------------------------------

@dataclass(frozen=True)
class NginxConfig:
    repo_dir: Path
    env_file: Path            # GENERATED_DIR/nginx.env
    bind_address: str
    https_port: str
    nginx_generated_dir: Path
    tls_dir: Path
    authelia_ca_dir: Path
    environment: dict[str, str] = field(default_factory=dict)
    frontend_subnet: str = ""


def frontend_network(subnet: str = "") -> str:
    entries: list = [
        ("NetworkName", FRONTEND),
        "Lower metric than the user networks (100): Nginx's default route stays here.",
        ("Options", f"metric={FRONTEND_METRIC}"),
    ]
    if subnet:
        entries.append(("Subnet", subnet))
    return render(["Generated by scripts/install-units.py. Do not edit."], [
        ("Unit", [("Description", "Remote browser: Nginx's network (published port, Authelia)")]),
        ("Network", entries),
    ])


def nginx_volumes(cfg: NginxConfig) -> list[tuple[str, str, str]]:
    r = cfg.repo_dir
    return [
        (f"{r}/nginx/nginx.conf", "/etc/nginx/nginx.conf", "ro,z"),
        (f"{r}/nginx/templates", "/etc/nginx/templates", "ro,z"),
        (f"{r}/nginx/snippets", "/etc/nginx/snippets", "ro,z"),
        (f"{r}/nginx/html", "/usr/share/nginx/remote-browser", "ro,z"),
        # User -> browser map files (*.map), see nginx.conf. Empty = nobody has a browser.
        (str(cfg.nginx_generated_dir), "/etc/nginx/generated", "ro,z"),
        # Certificate presented to the reverse proxy, which pins it (docs/apache-authelia.md).
        (str(cfg.tls_dir), "/etc/nginx/tls", "ro,z"),
        # CA certificate(s) for an https:// AUTHELIA_AUTHZ_URL signed by a private CA.
        (str(cfg.authelia_ca_dir), "/etc/nginx/authelia-ca", "ro,z"),
    ]


NGINX_TMPFS = ("/etc/nginx/conf.d:size=1m", "/var/cache/nginx:size=64m", "/run:size=1m", "/tmp:size=16m")


def nginx_env(cfg: NginxConfig) -> str:
    """Podman env file: KEY=VALUE, taken literally (no quotes, no expansion)."""
    for k, v in cfg.environment.items():
        if "\n" in v:
            raise UnitError(f"{k}: newline in value")
    return "".join(f"{k}={v}\n" for k, v in cfg.environment.items())


def nginx_container(cfg: NginxConfig, sync_script: Path) -> str:
    for src, _, _ in nginx_volumes(cfg):
        safe("volume", src)
    entries: list = [
        ("ContainerName", NGINX),
        ("Image", NGINX_IMAGE),
        ("Network", f"{FRONTEND}.network"),
        "Only the reverse proxy may connect (TRUSTED_PROXY, enforced by Nginx; the host firewall too).",
        ("PublishPort", f"{safe('BIND_ADDRESS', cfg.bind_address)}:{safe('HTTPS_PORT', cfg.https_port)}:443"),
        ("EnvironmentFile", safe("env file", str(cfg.env_file))),
    ]
    entries += [("Volume", f"{s}:{d}:{o}") for s, d, o in nginx_volumes(cfg)]
    entries += [
        "Root only to start: binds 443, renders the templates, then the workers run as \"nginx\".",
        ("NoNewPrivileges", "true"),
        ("DropCapability", "ALL"),
        ("AddCapability", "CHOWN SETGID SETUID NET_BIND_SERVICE"),
        ("ReadOnly", "true"),
        *[("Tmpfs", t) for t in NGINX_TMPFS],
        ("PidsLimit", "256"),
        ("HealthCmd", "wget -q -O /dev/null http://127.0.0.1:8081/healthz"),
        ("HealthInterval", "30s"),
        ("HealthTimeout", "5s"),
        ("LogDriver", "journald"),
    ]
    return render(["Generated by scripts/install-units.py. Do not edit."], [
        ("Unit", [
            ("Description", "Remote browser: Nginx (Authelia auth_request, per-user routing)"),
            ("Wants", "network-online.target"),
            ("After", f"network-online.target {EGRESS_UNIT}"),
        ]),
        ("Container", entries),
        ("Service", [
            ("Restart", "always"),
            "A new Nginx container is on no user network: join them all (failures are logged, not fatal).",
            ("ExecStartPost", f"-{safe('sync script', str(sync_script))} --attach-only"),
        ]),
        ("Install", [("WantedBy", "multi-user.target")]),
    ])


def nginx_test_command(cfg: NginxConfig) -> list[str]:
    """`nginx -t` in a throwaway container with Nginx's mounts and environment, on no network."""
    # With --network none Podman gives the container no /etc/resolv.conf, where the entrypoint looks
    # for NGINX_LOCAL_RESOLVERS: name one instead (-e overrides the env file).
    cmd = ["podman", "run", "--rm", "--network", "none", "--read-only", "--env-file", str(cfg.env_file),
           "-e", "NGINX_ENTRYPOINT_LOCAL_RESOLVERS=", "-e", "NGINX_LOCAL_RESOLVERS=127.0.0.1"]
    for s, d, o in nginx_volumes(cfg):
        cmd += ["-v", f"{s}:{d}:{o}"]
    for t in NGINX_TMPFS:
        cmd += ["--tmpfs", t]
    return cmd + [NGINX_IMAGE, "nginx", "-t"]


# --- validation ------------------------------------------------------------------------------------

def generator() -> str | None:
    return next((g for g in GENERATORS if os.access(g, os.X_OK)), None)


def validate(units: dict[str, str]) -> str:
    """Run Podman's Quadlet generator over these files alone (QUADLET_UNIT_DIRS) and return its output.
    Raises UnitError with the generator's messages if it rejects any of them."""
    gen = generator()
    if gen is None:
        raise UnitError("Podman's Quadlet generator not found (is podman installed?)")
    tmp = Path(tempfile.mkdtemp(prefix="rb-quadlet-"))
    try:
        for name, content in units.items():
            (tmp / name).write_text(content)
        env = {**os.environ, "QUADLET_UNIT_DIRS": str(tmp)}
        proc = subprocess.run([gen, "--dryrun"], capture_output=True, text=True, env=env)
        if proc.returncode != 0:
            lines = [ln for ln in proc.stderr.splitlines() if "Loading source unit file" not in ln]
            raise UnitError("; ".join(ln.split(": ", 1)[-1] for ln in lines).replace(str(tmp) + "/", "") or
                            f"generator exit {proc.returncode}")
        return proc.stdout
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
